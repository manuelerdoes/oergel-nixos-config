# remote-desktop: a separate, invisible desktop for working from home.
#
#   remote-desktop start [WIDTHxHEIGHT]   start it (default 1920x1080)
#   remote-desktop stop                   end it (closes all of its windows)
#   remote-desktop status                 is it running?
#
# Run it over SSH. It starts Umbriel without a monitor ("headless"), with
# Noctalia, a virtual screen and wayvnc on port 5901. Nobody has to be logged
# in at the notebook, and its screen shows nothing of what you do.
#
# Connect from home (after the work VPN):
#   ssh -L 5901:localhost:5901 <user>@<notebook>      then: remote-desktop start
#   VNC viewer -> localhost:5901
set -euo pipefail

UNIT=remote-desktop
PORT=5901
OUTPUT=HEADLESS-1 # the name wlroots gives the first headless screen
UMBRIEL_CONFIG="$HOME/.config/umbriel/config.toml"

die() {
  echo "remote-desktop: $*" >&2
  exit 1
}

usage() {
  sed -n '1,5p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

is_running() { systemctl --user is-active --quiet "$UNIT"; }

listening() { [ -n "$(ss -Hltn "sport = :$PORT" 2>/dev/null)" ]; }

# Keyboard layout from the Umbriel config, as wayvnc wants it: layout[-variant]
keymap() {
  local layout variant
  layout="$(sed -n -E '/^layout = "/{s/^layout = "([^"]*)".*/\1/p;q}' "$UMBRIEL_CONFIG")"
  variant="$(sed -n -E '/^variant = "/{s/^variant = "([^"]*)".*/\1/p;q}' "$UMBRIEL_CONFIG")"
  printf '%s%s' "${layout:-us}" "${variant:+-$variant}"
}

start() {
  local size="${1:-1920x1080}" dir config
  [[ "$size" =~ ^[0-9]{3,5}x[0-9]{3,5}$ ]] || die "the size must look like 1920x1080."
  [ -r "$UMBRIEL_CONFIG" ] || die "no Umbriel config at $UMBRIEL_CONFIG."
  if is_running; then
    echo "Already running. Connect the VNC viewer to localhost:$PORT (through the SSH tunnel)."
    return
  fi

  # The normal Umbriel config, plus a virtual screen and this session's own
  # autostart (the included file is read first; values set here win).
  dir="${XDG_RUNTIME_DIR:?is not set. Log in through SSH or a normal session.}/remote-desktop"
  config="$dir/umbriel.toml"
  mkdir -p "$dir"
  cat >"$config" <<EOF
# Generated by remote-desktop. Your normal config plus a virtual screen.
[include]
files = ["$UMBRIEL_CONFIG"]

[general]
autostart = ["noctalia", "wayvnc -o $OUTPUT -k $(keymap) 127.0.0.1 $PORT"]
show_cheatsheet = false

[output.$OUTPUT]
mode = "$size"
EOF

  # A systemd user service: it survives a dropped SSH connection, and stopping
  # it closes everything started inside it. bash -l loads the normal login
  # environment (PATH, the session variables from the NixOS config).
  systemctl --user reset-failed "$UNIT" 2>/dev/null || true
  systemd-run --user --quiet --unit="$UNIT" \
    --description="Remote desktop (headless Umbriel)" \
    --setenv=WLR_BACKENDS=headless \
    --setenv=WLR_HEADLESS_OUTPUTS=1 \
    --setenv=WLR_LIBINPUT_NO_DEVICES=1 \
    bash -lc "exec umbriel -c '$config'"

  echo "Starting a $size desktop..."
  for _ in $(seq 1 30); do
    if listening; then
      echo "Ready. Connect the VNC viewer to localhost:$PORT (through the SSH tunnel)."
      echo "End it with: remote-desktop stop"
      return
    fi
    is_running || break
    sleep 1
  done
  echo "It didn't come up. The last log lines:" >&2
  journalctl --user -u "$UNIT" -n 30 --no-pager >&2 || true
  echo "Umbriel's own log: ~/.cache/umbriel/umbriel.log" >&2
  exit 1
}

stop() {
  if ! is_running; then
    echo "Not running."
    return
  fi
  systemctl --user stop "$UNIT"
  echo "Stopped."
}

status() {
  if is_running; then
    if listening; then
      echo "Running. VNC on localhost:$PORT (through the SSH tunnel)."
    else
      echo "Running, but VNC isn't listening on port $PORT yet. Log: journalctl --user -u $UNIT"
    fi
  else
    echo "Not running. Start it with: remote-desktop start [WIDTHxHEIGHT]"
  fi
}

case "${1:-}" in
  start) start "${2:-}" ;;
  stop) stop ;;
  status) status ;;
  -h | --help | help) usage 0 ;;
  *) usage 1 ;;
esac
